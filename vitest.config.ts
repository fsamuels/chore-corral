import { fileURLToPath } from 'node:url'
import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vitest/config'

export default defineConfig({
  // Only so coverage can parse .vue files that no test imports (they count
  // as 0% instead of being dropped); the tests themselves don't mount SFCs.
  plugins: [vue()],
  // Nuxt's path aliases, so coverage can transform app files that no test
  // imports (an unresolvable import drops the file from the report).
  resolve: {
    alias: {
      '~~': fileURLToPath(new URL('.', import.meta.url)),
      '~': fileURLToPath(new URL('./app', import.meta.url)),
      '#supabase/server': fileURLToPath(
        new URL(
          './node_modules/@nuxtjs/supabase/dist/runtime/server/services/index.js',
          import.meta.url,
        ),
      ),
    },
  },
  test: {
    environment: 'happy-dom',
    include: ['tests/**/*.test.ts'],
    coverage: {
      provider: 'v8',
      // Whole-app coverage: every source file under app/ and server/, with
      // files no test loads counted as 0% (see DECISIONS.md).
      include: ['app/**/*.{ts,vue}', 'server/**/*.ts'],
      // Generated by `supabase gen types` — not hand-written code.
      exclude: ['app/types/**'],
      reporter: ['text-summary', 'json-summary'],
      reportsDirectory: 'coverage',
    },
  },
})

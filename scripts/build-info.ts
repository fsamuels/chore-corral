/**
 * Build-time facts for the About page: which commit this build came from,
 * when it was built, and a handful of codebase trivia (lines of code,
 * component counts, test cases, …).
 *
 * Runs once, inside nuxt.config.ts, while `nuxt build` (or `nuxt dev`) is
 * loading — the result is baked into app config, so the About page never
 * touches git or the filesystem at runtime (Vercel's serverless functions
 * have neither).
 *
 * Commit metadata prefers Vercel's `VERCEL_GIT_*` env vars and falls back to
 * local `git`. Vercel clones shallowly, so anything that needs full history
 * (commit count, first commit date) comes back `null` on a shallow clone
 * rather than a misleadingly small number; the page hides those rows.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { extname, join, relative } from 'node:path'

export interface LanguageLines {
  language: string
  files: number
  lines: number
}

export interface CodebaseStats {
  languages: LanguageLines[]
  totalFiles: number
  totalLines: number
  pages: number
  components: number
  composables: number
  services: number
  migrations: number
  testFiles: number
  testCases: number
  docsWords: number
  longestFile: { path: string; lines: number } | null
}

export interface BuildInfo {
  commitSha: string | null
  commitShortSha: string | null
  commitMessage: string | null
  commitDate: string | null
  branch: string | null
  builtAt: string
  commitCount: number | null
  firstCommitDate: string | null
  dependencies: number
  devDependencies: number
  nuxtVersion: string | null
  vueVersion: string | null
  vuetifyVersion: string | null
  code: CodebaseStats
  coverage: CoverageStats | null
}

export interface CoverageArea {
  /** `services`, `pages`, … for app/<dir>/; `app` for files directly in app/; `server`. */
  area: string
  files: number
  covered: number
  total: number
  pct: number
}

export interface CoverageStats {
  lines: number
  statements: number
  branches: number
  functions: number
  coveredLines: number
  totalLines: number
  /** Per-area line coverage, best-covered first. */
  areas: CoverageArea[]
}

interface CoverageMetric {
  total: number
  covered: number
  pct: number
}
type CoverageSummary = Record<
  string,
  Record<'lines' | 'statements' | 'branches' | 'functions', CoverageMetric>
>

const pct = (covered: number, total: number) =>
  total === 0 ? 0 : Math.round((covered / total) * 1000) / 10

export interface SourceFile {
  /** Repo-relative path with forward slashes, e.g. `app/pages/about.vue`. */
  path: string
  content: string
}

const LANGUAGES: Record<string, string> = {
  '.vue': 'Vue',
  '.ts': 'TypeScript',
  '.mjs': 'JavaScript',
  '.js': 'JavaScript',
  '.sql': 'SQL',
  '.css': 'CSS',
}

// Directories that hold hand-written source; generated/vendored output
// (node_modules, .nuxt, .output) never appears under these.
const SOURCE_DIRS = ['app', 'server', 'supabase', 'tests', 'scripts']
const SKIP_DIRS = new Set(['node_modules', '.temp', '.nuxt', '.output'])
// Generated by `supabase gen types` — counting it would inflate TypeScript
// by several hundred lines nobody wrote.
const SKIP_FILES = new Set(['app/types/database.types.ts'])

function countLines(content: string): number {
  if (content === '') return 0
  const lines = content.split('\n')
  return content.endsWith('\n') ? lines.length - 1 : lines.length
}

/** Matches `it(`, `test(`, `it.each(…)(`-style call sites at line start. */
const TEST_CASE = /^\s*(?:it|test)(?:\.\w+)*\s*\(/gm

/**
 * Pure summary of a set of source files plus the docs' markdown — split out
 * from the filesystem walk so it can be unit tested.
 */
export function summarizeCodebase(
  files: SourceFile[],
  docs: string[],
): CodebaseStats {
  const byLanguage = new Map<string, LanguageLines>()
  let longestFile: CodebaseStats['longestFile'] = null
  let testCases = 0

  for (const file of files) {
    const language = LANGUAGES[extname(file.path)]
    if (!language) continue
    const lines = countLines(file.content)
    const entry = byLanguage.get(language) ?? { language, files: 0, lines: 0 }
    entry.files += 1
    entry.lines += lines
    byLanguage.set(language, entry)
    if (!longestFile || lines > longestFile.lines) {
      longestFile = { path: file.path, lines }
    }
    if (file.path.startsWith('tests/') && file.path.endsWith('.test.ts')) {
      testCases += file.content.match(TEST_CASE)?.length ?? 0
    }
  }

  const languages = [...byLanguage.values()].sort((a, b) => b.lines - a.lines)
  const count = (predicate: (path: string) => boolean) =>
    files.filter((f) => predicate(f.path)).length

  return {
    languages,
    totalFiles: languages.reduce((sum, l) => sum + l.files, 0),
    totalLines: languages.reduce((sum, l) => sum + l.lines, 0),
    pages: count((p) => p.startsWith('app/pages/') && p.endsWith('.vue')),
    components: count(
      (p) => p.startsWith('app/components/') && p.endsWith('.vue'),
    ),
    composables: count((p) => p.startsWith('app/composables/')),
    services: count((p) => p.startsWith('app/services/')),
    migrations: count(
      (p) => p.startsWith('supabase/migrations/') && p.endsWith('.sql'),
    ),
    testFiles: count((p) => /^tests\/.*\.(test|spec)\.ts$/.test(p)),
    testCases,
    docsWords: docs.reduce(
      (sum, doc) => sum + (doc.match(/\S+/g)?.length ?? 0),
      0,
    ),
    longestFile,
  }
}

/**
 * Pure summary of Vitest's `coverage-summary.json` (json-summary reporter):
 * the totals, plus line coverage grouped by area. Keys are absolute paths, so
 * `root` is stripped to group them.
 */
export function summarizeCoverage(
  summary: CoverageSummary,
  root: string,
): CoverageStats | null {
  const total = summary.total
  if (!total) return null
  const prefix = root.endsWith('/') ? root : `${root}/`
  const areas = new Map<string, CoverageArea>()
  for (const [file, metrics] of Object.entries(summary)) {
    if (file === 'total') continue
    const parts = file.split('\\').join('/').replace(prefix, '').split('/')
    const area =
      (parts[0] === 'app' && parts.length > 2 ? parts[1] : parts[0]) ?? 'other'
    const entry = areas.get(area) ?? {
      area,
      files: 0,
      covered: 0,
      total: 0,
      pct: 0,
    }
    entry.files += 1
    entry.covered += metrics.lines.covered
    entry.total += metrics.lines.total
    areas.set(area, entry)
  }
  for (const entry of areas.values()) {
    entry.pct = pct(entry.covered, entry.total)
  }
  return {
    lines: pct(total.lines.covered, total.lines.total),
    statements: pct(total.statements.covered, total.statements.total),
    branches: pct(total.branches.covered, total.branches.total),
    functions: pct(total.functions.covered, total.functions.total),
    coveredLines: total.lines.covered,
    totalLines: total.lines.total,
    areas: [...areas.values()].sort(
      (a, b) => b.pct - a.pct || b.total - a.total,
    ),
  }
}

/**
 * Reads the report `pnpm build` produces by running `pnpm test:coverage`
 * first. Vitest clears the report directory at the start of a run and writes
 * no report when a test fails, so a failed run leaves nothing here and the
 * About page shows coverage as unavailable rather than a stale number.
 */
function readCoverage(root: string): CoverageStats | null {
  const summary = readJson(join(root, 'coverage', 'coverage-summary.json'))
  return summary ? summarizeCoverage(summary as CoverageSummary, root) : null
}

function walk(root: string, dir: string, out: SourceFile[]) {
  let entries: string[]
  try {
    entries = readdirSync(dir)
  } catch {
    return
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry)) continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      walk(root, full, out)
      continue
    }
    const path = relative(root, full).split('\\').join('/')
    if (SKIP_FILES.has(path) || !LANGUAGES[extname(path)]) continue
    out.push({ path, content: readFileSync(full, 'utf8') })
  }
}

function git(root: string, ...args: string[]): string | null {
  try {
    return execFileSync('git', args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return null
  }
}

function readJson(path: string): Record<string, unknown> | null {
  try {
    return JSON.parse(readFileSync(path, 'utf8'))
  } catch {
    return null
  }
}

function installedVersion(root: string, pkg: string): string | null {
  const json = readJson(join(root, 'node_modules', pkg, 'package.json'))
  return typeof json?.version === 'string' ? json.version : null
}

export function collectBuildInfo(root: string): BuildInfo {
  const env = process.env
  const sha = env.VERCEL_GIT_COMMIT_SHA || git(root, 'rev-parse', 'HEAD')
  const shallow = git(root, 'rev-parse', '--is-shallow-repository') !== 'false'

  const files: SourceFile[] = []
  for (const dir of SOURCE_DIRS) walk(root, join(root, dir), files)
  const docs: string[] = []
  for (const name of ['README.md', ...safeList(join(root, 'docs'))]) {
    if (!name.endsWith('.md')) continue
    const path =
      name === 'README.md' ? join(root, name) : join(root, 'docs', name)
    try {
      docs.push(readFileSync(path, 'utf8'))
    } catch {
      // Missing doc — just skip it.
    }
  }

  const pkg = readJson(join(root, 'package.json')) ?? {}
  const depCount = (key: string) =>
    Object.keys((pkg[key] as Record<string, string> | undefined) ?? {}).length

  return {
    commitSha: sha,
    commitShortSha: sha ? sha.slice(0, 7) : null,
    commitMessage:
      env.VERCEL_GIT_COMMIT_MESSAGE?.split('\n')[0] ||
      git(root, 'log', '-1', '--format=%s'),
    commitDate: git(root, 'log', '-1', '--format=%cI'),
    branch:
      env.VERCEL_GIT_COMMIT_REF ||
      git(root, 'rev-parse', '--abbrev-ref', 'HEAD'),
    builtAt: new Date().toISOString(),
    commitCount: shallow
      ? null
      : Number(git(root, 'rev-list', '--count', 'HEAD')) || null,
    firstCommitDate: shallow
      ? null
      : (git(root, 'log', '--reverse', '--format=%cI')?.split('\n')[0] ?? null),
    dependencies: depCount('dependencies'),
    devDependencies: depCount('devDependencies'),
    nuxtVersion: installedVersion(root, 'nuxt'),
    vueVersion: installedVersion(root, 'vue'),
    vuetifyVersion: installedVersion(root, 'vuetify'),
    code: summarizeCodebase(files, docs),
    coverage: readCoverage(root),
  }
}

function safeList(dir: string): string[] {
  try {
    return readdirSync(dir)
  } catch {
    return []
  }
}
